inline int setup(void)
{
    OSCCON = 0b01110001;
    CM1CON0_init(0x00);
    CM2CON0_init(0x00);
    porta_init(0x01, 0x00);
    portb_init(0x00, 0x00);
    portc_init(0x80, 0x40);
    anselH_init(0x00);
    anselL_init(0x01);
    uart_init();
    ccp2con_init(0x00);
    tmr2_init(0x00);
    init_PWM2_(79);
    set_PWM2_Duty(0);
    adc_module_init();
    return 0;
}

int main(void)
{   
    setup();
    unsigned char   fan_state       = FAN_25;
    unsigned int    adc_avrg        = 0;
    unsigned char   temp_real       = 0;
    unsigned char   temp_display    = 0;
    packet_t        frame           = {0};

    set_fan_percent(100); 
    __delay_ms(2000);
    set_fan_percent(25);

    while(1)
    {
        static uint8_t counter = 0;
        for (unsigned char i = 0; i < 16; i++) 
        {
            ADCON0 |= (1 << 1);
            while(ADCON0 & (1 << 1));
            adc_avrg += ((unsigned int)(ADRESH << 8) | ADRESL);    
        }
        
        adc_avrg /= 16;

        temp_real = temp_values[adc_avrg];

        if(temp_display != temp_real)
        {
            counter++;
            if (counter >= 10)
            {
                temp_display = temp_real;
                counter = 0;
            }
        } else counter = 0;

        tm1637_display_number(temp_display, BRIGHTNESS_4);
        
        switch(fan_state)
        {
            case FAN_25:
                if (temp_display >= 42)
                {
                    fan_state = FAN_50;
                    set_fan_percent(50);
                }
            break;
            case FAN_50:
                if (temp_display >= 45)
                {
                    fan_state = FAN_75;
                    set_fan_percent(75);
                }
                if (temp_display <= 40)
                {
                    fan_state = FAN_25;
                    set_fan_percent(25);
                }
                break;
            case FAN_75:    
                if (temp_display >= 50)
                {
                    fan_state = FAN_100;
                    set_fan_percent(100);
                }
                if (temp_display <= 45)
                {
                    fan_state = FAN_50;
                    set_fan_percent(50);
                }
            break;
            case FAN_100:
                if (temp_display < 47)
                {
                    fan_state = FAN_75;
                    set_fan_percent(75);
                }
            break;
        }

        frame.f.cmd     =   STATUS_;
        frame.f.fan     =   fan_state;
        frame.f.temp    =   temp_display;
        frame.f.crc     =   crcx(frame.raw, 3);
            
        send_byte(0xAA);
        send_byte(0x55);

        send_byte(frame.f.cmd);
        send_byte(frame.f.temp);
        send_byte(frame.f.fan);
        send_byte(frame.f.crc);

        adc_avrg = 0;
        __delay_ms(10);
    }
    return 0;
}
